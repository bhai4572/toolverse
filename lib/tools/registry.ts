export function getToolBySlug(slug: string): ToolDefinition | undefined {
  return TOOLS.find((tool) => tool.slug === slug);
}

export function getToolById(id: string): ToolDefinition | undefined {
  return TOOLS.find((tool) => tool.id === id);
}

export function getToolsByCategory(categorySlug: string): ToolDefinition[] {
  return TOOLS.filter((tool) => tool.categorySlug === categorySlug && tool.status === 'live');
}

export function getLiveTools(): ToolDefinition[] {
  return TOOLS.filter((tool) => tool.status === 'live');
}

export function getFeaturedTools(): ToolDefinition[] {
  return TOOLS.filter((tool) => tool.featured && tool.status === 'live');
}

export function getPopularTools(): ToolDefinition[] {
  return TOOLS.filter((tool) => tool.popular && tool.status === 'live');
}

export function searchTools(query: string): ToolDefinition[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return TOOLS.filter((tool) => {
    if (tool.status !== 'live') return false;
    return (
      tool.canonicalName.toLowerCase().includes(q) ||
      tool.shortDescription.toLowerCase().includes(q) ||
      tool.keywords.some((k) => k.toLowerCase().includes(q)) ||
      tool.aliases.some((a) => a.toLowerCase().includes(q))
    );
  });
}
